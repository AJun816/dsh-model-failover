/** Generate src/version.ts from package.json so the shipped code always
 *  reports the version it was built from (heartbeat log + GUI card). */
import { readFileSync, writeFileSync } from 'node:fs'

const pkg = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'))
const out = `// AUTO-GENERATED by scripts/write-version.mjs — do not edit; regenerated on every build.
/** The version of this plugin build (single source: package.json). */
export const VERSION = '${pkg.version}'
`
writeFileSync(new URL('../src/version.ts', import.meta.url), out)
console.log('version.ts ->', pkg.version)
